"""
Organise the LLM-generated imagen prompts into clean upload-ready files.

Source of truth: Apps/StimuliGenerator/generation_log.jsonl
Output:          evaluation/results/imagen_prompts/
  - paired_prompts.jsonl     : one line per (session, position) — 160 paired prompts
  - paired_prompts.csv       : same content, CSV format
  - README.md                : describes the dataset, schema, provenance
"""
import json
import csv
from pathlib import Path

LOG = Path("/Users/noman/Documents/Thesis/Apps/StimuliGenerator/generation_log.jsonl")
OUT = Path("/Users/noman/Documents/Thesis/evaluation/results/imagen_prompts")
OUT.mkdir(parents=True, exist_ok=True)

def task_kind(task):
    t = (task or "").lower()
    return "skii" if any(k in t for k in ("ski", "snowboard")) else "jar"

pairs = []
sessions_with_prompts = 0
sessions_total = 0
with open(LOG) as f:
    for line in f:
        d = json.loads(line)
        sessions_total += 1
        pp = d.get("paired_prompts") or []
        if len(pp) != 5:
            continue
        sessions_with_prompts += 1
        session_id = d.get("session_id") or d.get("started_at") or ""
        task = d.get("frontend_request", {}).get("task", "")
        reqs = d.get("frontend_request", {}).get("requirements", [])
        started = d.get("started_at", "")
        completed = d.get("completed_at", "")
        for p in pp:
            pairs.append({
                "session_id": session_id,
                "started_at": started,
                "completed_at": completed,
                "task": task,
                "task_kind": task_kind(task),
                "requirements_count": len(reqs),
                "position": p["position"],
                "nc_sentence": p.get("nc_sentence", ""),
                "vc_sentence": p.get("vc_sentence", ""),
                "nc_prompt": p.get("nc_prompt", ""),
                "vc_prompt": p.get("vc_prompt", ""),
                "nc_prompt_word_count": len(str(p.get("nc_prompt", "")).split()),
                "vc_prompt_word_count": len(str(p.get("vc_prompt", "")).split()),
            })

print(f"Total session entries in log:        {sessions_total}")
print(f"Sessions with complete paired prompts: {sessions_with_prompts}")
print(f"Total paired prompts written:        {len(pairs)}")
print(f"Total individual prompts (NC + VC):  {len(pairs)*2}")

# JSONL — line-per-pair
out_jsonl = OUT / "paired_prompts.jsonl"
with open(out_jsonl, "w") as f:
    for p in pairs:
        f.write(json.dumps(p, ensure_ascii=False) + "\n")
print(f"Written: {out_jsonl}")

# CSV — same content
out_csv = OUT / "paired_prompts.csv"
with open(out_csv, "w", newline="", encoding="utf-8") as f:
    w = csv.DictWriter(f, fieldnames=list(pairs[0].keys()))
    w.writeheader()
    w.writerows(pairs)
print(f"Written: {out_csv}")

# README
readme = f"""# LLM-Generated Imagen Prompts — Dataset

This directory holds the {len(pairs)*2} image-generation prompts that the
StimuliGenerator system produced via its image-prompt translator
(`image_system_prompt.py`) during the participant-facing corpus generation
described in Chapter 4 of the thesis.

## Provenance

Every prompt was generated by the deterministic visual-prompt translator
inside `image_generator.py:_get_paired_imagen_prompts()`. For each sentence
position $S_i$ (i = 1..5) of every run, the translator received the matched
(NC sentence, VC sentence) pair and emitted a paired JSON object
`{{"nc_prompt": "...", "vc_prompt": "..."}}` in a single Gemini call.

**Source of truth:** every prompt is recorded verbatim in:

  `Apps/StimuliGenerator/generation_log.jsonl`

inside each session's `paired_prompts[]` array. The files in this folder
are derived from that log; the log is the immutable record of what the
LLM actually generated at request time.

## Coverage

- {sessions_total} session entries in `generation_log.jsonl`
- {sessions_with_prompts} sessions with a complete 5-position `paired_prompts[]` array
- {len(pairs)} paired prompts ({len(pairs)*2} individual prompts: half NC, half VC)
- 2 design tasks: `jar` (stroke-patient assistive tool) and `skii` (winter-sports)

## Files

| File | Description |
|---|---|
| `paired_prompts.jsonl` | One line per (session × position) — primary dataset |
| `paired_prompts.csv`   | Same content as CSV with quoted long fields |
| `per_prompt.json`      | Flattened 320-row view with per-prompt AL and Brysbaert scores |
| `summary.json`         | Aggregate run-level metadata |
| `full_analysis.txt`    | Output of `analyze_imagen_prompts.py` |
| `README.md`            | This file |

## Schema (paired_prompts.jsonl)

Each line is one JSON object with the following fields:

| Field | Type | Description |
|---|---|---|
| `session_id` | string | Session identifier from the log |
| `started_at` | string | ISO-8601 timestamp when the request started |
| `completed_at` | string | ISO-8601 timestamp when the request finished |
| `task` | string | Full design task description fed to the system |
| `task_kind` | string | `jar` or `skii` |
| `requirements_count` | int | Number of requirements in the request |
| `position` | string | Sentence position: `S1` through `S5` |
| `nc_sentence` | string | The NC source sentence at this position |
| `vc_sentence` | string | The VC source sentence at this position |
| `nc_prompt` | string | The LLM-generated NC image prompt |
| `vc_prompt` | string | The LLM-generated VC image prompt |
| `nc_prompt_word_count` | int | Word count of `nc_prompt` |
| `vc_prompt_word_count` | int | Word count of `vc_prompt` |

## How to regenerate

Run from the thesis root:

    python3 evaluation/scripts/analyze_imagen_prompts.py

That script reads `generation_log.jsonl` and rebuilds this dataset together
with the full statistical analysis reported in Chapter 4, Section 4.5.
"""
(OUT / "README.md").write_text(readme)
print(f"Written: {OUT / 'README.md'}")
